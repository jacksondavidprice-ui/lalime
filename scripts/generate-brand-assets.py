#!/usr/bin/env python3
"""Generate web/Electron/installer icons from Jackson's Lalime master logo.

Does not copy the 8MB master into the renderer. Run:
  python3 scripts/generate-brand-assets.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
UPLOADS = Path("/home/ubuntu/.cursor/projects/workspace/uploads")
MASTER_CANDIDATES = [
    UPLOADS / "Llime_Logo_72c6.png",
    ROOT / "uploads" / "Llime_Logo.png",
    ROOT / "brand" / "Llime_Logo.png",
]
MARK_CANDIDATES = [
    UPLOADS / "logo-mark_0040.png",
    ROOT / "uploads" / "logo-mark.png",
]

SIZES_WEB = [32, 48, 64, 128, 256]
SIZES_ICO = [16, 24, 32, 48, 64, 128, 256]
ELECTRON_PNG = 512


def find_master() -> Path:
    for p in MASTER_CANDIDATES:
        if p.exists():
            return p
    raise SystemExit("Master logo not found")


def content_bbox(im: Image.Image, threshold: int = 28) -> tuple[int, int, int, int]:
    """Tight bbox around non-near-black opaque pixels."""
    rgba = im.convert("RGBA")
    w, h = rgba.size
    px = rgba.load()
    minx, miny, maxx, maxy = w, h, 0, 0
    step = max(1, min(w, h) // 800)
    found = False
    for y in range(0, h, step):
        for x in range(0, w, step):
            r, g, b, a = px[x, y]
            if a > 16 and (r + g + b) > threshold:
                minx = min(minx, x)
                miny = min(miny, y)
                maxx = max(maxx, x)
                maxy = max(maxy, y)
                found = True
    if not found:
        return (0, 0, w, h)
    pad = int(max(w, h) * 0.02)
    return (
        max(0, minx - pad),
        max(0, miny - pad),
        min(w, maxx + pad + 1),
        min(h, maxy + pad + 1),
    )


def square_canvas(im: Image.Image, size: int, sharpen_small: bool = True) -> Image.Image:
    """Fit cropped logo into a transparent square of `size`."""
    rgba = im.convert("RGBA")
    box = content_bbox(rgba)
    cropped = rgba.crop(box)
    # Keep a little breathing room inside the square
    side = max(cropped.size)
    pad = int(side * 0.06)
    canvas = Image.new("RGBA", (side + pad * 2, side + pad * 2), (0, 0, 0, 0))
    ox = (canvas.size[0] - cropped.size[0]) // 2
    oy = (canvas.size[1] - cropped.size[1]) // 2
    canvas.paste(cropped, (ox, oy), cropped)

    out = canvas.resize((size, size), Image.Resampling.LANCZOS)
    if sharpen_small and size <= 48:
        out = ImageEnhance.Contrast(out).enhance(1.12)
        out = out.filter(ImageFilter.UnsharpMask(radius=0.6, percent=120, threshold=2))
    elif sharpen_small and size <= 128:
        out = ImageEnhance.Contrast(out).enhance(1.05)
    return out


def save_png(im: Image.Image, path: Path, optimize: bool = True) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, format="PNG", optimize=optimize)
    print(f"wrote {path} ({path.stat().st_size} bytes)")


def main() -> None:
    master_path = find_master()
    master = Image.open(master_path)
    print(f"master: {master_path} {master.size}")

    # Archive a reference copy outside the renderer bundle (source of truth for regen).
    brand_dir = ROOT / "brand"
    brand_dir.mkdir(exist_ok=True)
    # Store a downscaled archive (1024) + note — never the full 8MB in public/src.
    archive = square_canvas(master, 1024, sharpen_small=False)
    save_png(archive, brand_dir / "logo-master-1024.png")
    (brand_dir / "README.md").write_text(
        "# Brand assets\n\n"
        "`logo-master-1024.png` is derived from Jackson's full-res master for regen.\n"
        "Web/Electron icons live in `public/` and `build/` — generated by "
        "`scripts/generate-brand-assets.py`.\n"
        "Do not put the 8MB master under `src/` or `public/`.\n",
        encoding="utf-8",
    )

    public = ROOT / "public"
    assets = ROOT / "src" / "assets"
    build = ROOT / "build"

    # Primary web mark (256) — used by React Logo component
    mark256 = square_canvas(master, 256)
    save_png(mark256, public / "logo-mark.png")
    save_png(mark256, assets / "logo-mark.png")

    for s in SIZES_WEB:
        if s == 256:
            continue
        save_png(square_canvas(master, s), public / f"logo-mark-{s}.png")

    # Favicon set
    save_png(square_canvas(master, 32), public / "favicon-32.png")
    save_png(square_canvas(master, 16), public / "favicon-16.png")
    save_png(square_canvas(master, 180), public / "apple-touch-icon.png")

    ico_images = [square_canvas(master, s) for s in SIZES_ICO]
    ico_path = public / "favicon.ico"
    ico_images[-1].save(
        ico_path,
        format="ICO",
        sizes=[(im.width, im.height) for im in ico_images],
        append_images=ico_images[:-1],
    )
    print(f"wrote {ico_path} ({ico_path.stat().st_size} bytes)")

    # Electron / installer
    icon512 = square_canvas(master, ELECTRON_PNG, sharpen_small=False)
    save_png(icon512, build / "icon.png")
    # Also 256 for Windows tray-ish uses
    save_png(square_canvas(master, 256), build / "icon-256.png")

    build_ico = build / "icon.ico"
    ico_images[-1].save(
        build_ico,
        format="ICO",
        sizes=[(im.width, im.height) for im in ico_images],
        append_images=ico_images[:-1],
    )
    print(f"wrote {build_ico} ({build_ico.stat().st_size} bytes)")

    # Optional: keep the old 256 mark as a reference if present
    for p in MARK_CANDIDATES:
        if p.exists():
            print(f"note: website mark available at {p} (generator prefers master)")
            break


if __name__ == "__main__":
    main()
